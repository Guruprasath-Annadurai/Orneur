class CorruptRecordError(Exception):
    """Raised internally per-line; always caught by `stream_records()` and
    converted into a `ProcessingReport.corrupt_records` entry -- never
    propagates out and never halts the stream."""


def _atomic_write_bytes(path: Path, data: bytes) -> None:
    """The established mkstemp + fsync + os.replace discipline (Sprint 1 /
    Audit #016's `save_training_state` pattern), reimplemented here for a
    plain artifact file rather than a torch checkpoint. Used for files
    that are REPLACED wholesale (the progress snapshot, never a shard
    file, which is append-only -- see `_flush_pending_shard_rows()`)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.tmp-")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        tmp.chmod(0o600)
        os.replace(tmp, path)
        dir_fd = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(dir_fd)
        finally:
            os.close(dir_fd)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


@dataclass
class ProcessingReport:
    """Explicit, structured failure reporting -- every record is
    accounted for in exactly one bucket; nothing is silently dropped
    without being counted somewhere."""
    lines_read: int = 0
    corrupt_records: int = 0
    corrupt_samples: list[str] = field(default_factory=list)  # bounded sample of reasons, not unbounded
    exact_duplicates: int = 0
    near_duplicates: int = 0
    quality_rejected: int = 0
    pii_secret_rejected: int = 0
    kept: int = 0
    resume_offset: int = 0  # line number to resume from on restart

    def record_corrupt(self, reason: str) -> None:
        self.corrupt_records += 1
        if len(self.corrupt_samples) < 20:
            self.corrupt_samples.append(reason)


def stream_records(path: Path, *, resume_from_line: int = 0) -> Iterator[tuple[int, str]]:
    """Memory-bounded streaming reader: yields (line_number, text) one
    line at a time, never loading the whole file into memory.
    `resume_from_line` skips already-processed lines (restart safety) --
    a caller resuming a prior run passes the `resume_offset` their last
    `ProcessingReport` recorded. Malformed JSON lines are skipped with a
    recorded reason, never raised past this function."""
    with open(path, encoding="utf-8") as f:
        for line_number, raw_line in enumerate(f):
            if line_number < resume_from_line:
                continue
            raw_line = raw_line.strip()
            if not raw_line:
                continue
            try:
                rec = json.loads(raw_line)
            except json.JSONDecodeError:
                yield line_number, ""  # caller distinguishes via a sentinel check below
                continue
            text = rec.get("text") if isinstance(rec, dict) else None
            if not isinstance(text, str) or not text.strip():
                yield line_number, ""
                continue
            yield line_number, text


def deterministic_shard(normalized_text: str, *, num_shards: int) -> int:
    """A pure function of the record's own normalized content -- the same
    record always lands in the same shard, regardless of input file
    order, run count, or process. Not a function of position/index, which
    would make shard assignment depend on upstream ordering."""
    if num_shards < 1:
        raise ValueError(f"num_shards must be >= 1, got {num_shards}")
    digest = hashlib.sha256(normalized_text.encode("utf-8")).hexdigest()
    return int(digest[:8], 16) % num_shards


def deterministic_split(normalized_text: str, *, train_pct: int = 90, val_pct: int = 5) -> str:
    """Deterministic train/validation/test assignment, purely a function
    of record content -- reproducible across re-runs, and (since it does
    not depend on any other record) incapable of leaking a record across
    splits no matter how many times the pipeline is re-run or re-ordered."""
    if train_pct + val_pct > 100 or train_pct < 0 or val_pct < 0:
        raise ValueError(f"train_pct+val_pct must be <= 100 and both >= 0, got {train_pct}/{val_pct}")
    digest = hashlib.sha256(("split:" + normalized_text).encode("utf-8")).hexdigest()
    bucket = int(digest[:8], 16) % 100
    if bucket < train_pct:
        return "train"
    if bucket < train_pct + val_pct:
        return "validation"
    return "test"


def _shard_path(output_dir: Path, shard_idx: int, split_name: str) -> Path:
    return output_dir / f"shard-{shard_idx:04d}-{split_name}.jsonl"


def _open_progress_db(output_dir: Path) -> sqlite3.Connection:
    """The single durable source of truth for this `output_dir`'s
    processing state. `isolation_level=None` (autocommit OFF by default
    in the sense that we issue explicit BEGIN/COMMIT) gives this module
    full control over transaction boundaries, matching exactly where
    `process_corpus()` wants a batch to be atomic."""
    output_dir.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(output_dir / PROGRESS_DB_NAME, isolation_level=None)
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA synchronous=FULL")  # durability over raw speed -- this is a crash-safety primitive
    conn.execute("""
        CREATE TABLE IF NOT EXISTS progress (
            id INTEGER PRIMARY KEY CHECK (id = 0), resume_offset INTEGER NOT NULL,
            lines_read INTEGER NOT NULL, corrupt_records INTEGER NOT NULL,
            exact_duplicates INTEGER NOT NULL, near_duplicates INTEGER NOT NULL,
            quality_rejected INTEGER NOT NULL, pii_secret_rejected INTEGER NOT NULL,
            kept INTEGER NOT NULL
        )
    """)
    conn.execute("CREATE TABLE IF NOT EXISTS seen_exact (exact_key TEXT PRIMARY KEY)")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS kept_records (
            seq INTEGER PRIMARY KEY AUTOINCREMENT, shard INTEGER NOT NULL,
            split TEXT NOT NULL, normalized_text TEXT NOT NULL, flushed INTEGER NOT NULL DEFAULT 0
        )
    """)
    conn.execute("CREATE TABLE IF NOT EXISTS shard_file_safe_offsets (path TEXT PRIMARY KEY, safe_byte_offset INTEGER NOT NULL)")
    # Antigravity Audit #71 (AUDIT-P0-03): a pre-existing output_dir from
    # before this column existed gets it added, defaulting to '' -- which
    # deliberately does NOT match any real file's computed digest (see
    # _hash_file_prefix()'s docstring), so the FIRST recovery check against
    # a legacy output_dir fails closed and verifies/regenerates once,
    # rather than silently trusting an un-verified prior offset record.
    existing_cols = {row[1] for row in conn.execute("PRAGMA table_info(shard_file_safe_offsets)").fetchall()}
    if "safe_byte_digest" not in existing_cols:
        conn.execute("ALTER TABLE shard_file_safe_offsets ADD COLUMN safe_byte_digest TEXT NOT NULL DEFAULT ''")
    # P0-02 fix: durably persists the TAIL of the near-duplicate sliding
    # window (bounded to NEAR_DUP_WINDOW entries) so a resumed run
    # inherits the real window state a crash interrupted, instead of
    # starting from an empty window -- see _load_near_dup_window_tail()'s
    # own docstring for the reproduced defect this closes.
    conn.execute("CREATE TABLE IF NOT EXISTS near_dup_window (seq INTEGER PRIMARY KEY AUTOINCREMENT, line_number INTEGER NOT NULL, normalized_text TEXT NOT NULL)")
    return conn


def _load_near_dup_window_tail(conn: sqlite3.Connection) -> list[tuple[int, str, frozenset]]:
    """P0-02 fix: independently reproduced before this fix -- the
    near-duplicate sliding window was held ONLY in process-local memory
    and reset to empty on every `process_corpus()` call. A record
    processed just after a restart boundary was therefore never compared
    against the real records that immediately preceded it in an
    uninterrupted run, so a genuinely near-duplicate record could be
    silently KEPT after a resume where an uninterrupted run would have
    rejected it -- directly reproduced: an uninterrupted run over one
    synthetic corpus reported 1 near-duplicate and kept 6 records; the
    SAME corpus, processed via a resume partway through, reported 0
    near-duplicates and kept 7 -- a different logical corpus. Reloads
    the durably-persisted tail (bounded to `NEAR_DUP_WINDOW` entries, the
    same bound the in-memory window itself enforces) so a resumed run's
    window starts in the SAME state an uninterrupted run's would be in
    at that point."""
    rows = conn.execute("SELECT line_number, normalized_text FROM near_dup_window ORDER BY seq").fetchall()
    return [(line_number, text, frozenset(word_ngrams(text, NEAR_DUP_WORD_NGRAM))) for line_number, text in rows]


def _load_progress(conn: sqlite3.Connection) -> ProcessingReport:
    row = conn.execute("SELECT resume_offset, lines_read, corrupt_records, exact_duplicates, near_duplicates, quality_rejected, pii_secret_rejected, kept FROM progress WHERE id = 0").fetchone()
    if row is None:
        return ProcessingReport()
    resume_offset, lines_read, corrupt, exact_dup, near_dup, quality_rej, pii_rej, kept = row
    return ProcessingReport(
        lines_read=lines_read, corrupt_records=corrupt, exact_duplicates=exact_dup, near_duplicates=near_dup,
        quality_rejected=quality_rej, pii_secret_rejected=pii_rej, kept=kept, resume_offset=resume_offset,
    )


_EMPTY_SHA256 = hashlib.sha256(b"").hexdigest()


def _hash_file_prefix(path: Path, n: int) -> str:
    """Streams the first `n` bytes of `path` (or the whole file if it is
    shorter than `n`) and returns their SHA-256 hex digest -- never loads
    more than a fixed chunk size into memory at once. Used both to record
    a shard file's TRUE content digest at a known-good byte offset
    (`_flush_pending_shard_rows()`) and to verify that content hasn't
    silently changed since (`_verify_and_recover_missing_or_corrupted_shard_output()`).
    Hashing only the first `n` bytes (not the whole current file) matters
    because this is called BEFORE `_truncate_partial_shard_writes()` has
    had a chance to cut away any not-yet-recorded trailing bytes a
    crashed write may have left behind -- comparing only the prefix a
    prior call actually recorded as safe avoids a false-positive mismatch
    against bytes that were never claimed to be safe in the first place."""
    h = hashlib.sha256()
    remaining = n
    if not path.exists():
        return _EMPTY_SHA256 if n == 0 else h.hexdigest()  # unreachable for n>0 by callers, but never crash
    with open(path, "rb") as f:
        while remaining > 0:
            chunk = f.read(min(1024 * 1024, remaining))
            if not chunk:
                break
            h.update(chunk)
            remaining -= len(chunk)
    return h.hexdigest()


def _truncate_partial_shard_writes(output_dir: Path, conn: sqlite3.Connection) -> None:
    """Crash-safety recovery step, run once at the START of every
    `process_corpus()` call (whether this is a fresh run or a resume):
    for every shard file this `output_dir` has ever recorded a
    known-good byte offset for, truncate it back to that exact offset
    FIRST, before any new flush is attempted. This removes any
    partially-written trailing bytes a crash mid-`write()` could have
    left behind, so the subsequent idempotent re-flush (from SQLite's
    durable `kept_records` truth) never appends on top of a corrupt
    partial line."""
    for path_str, safe_offset in conn.execute("SELECT path, safe_byte_offset FROM shard_file_safe_offsets").fetchall():
        p = Path(path_str)
        if p.exists() and p.stat().st_size > safe_offset:
            with open(p, "r+b") as f:
                f.truncate(safe_offset)
                f.flush()
                os.fsync(f.fileno())


def _verify_and_recover_missing_or_corrupted_shard_output(output_dir: Path, conn: sqlite3.Connection) -> None:
    """P0-03 fix (Native-Authorization-Convergence): independently
    reproduced before this fix -- externally deleting (or truncating) a
    shard file AFTER it was durably flushed left `process_corpus()`
    completely unaware: `report.kept` and the returned `kept_records`
    list (re-read from SQLite's own `kept_records` table, not from the
    filesystem) still reported the full count, even though the actual
    processed-shard BYTES a downstream consumer would read no longer
    existed on disk at all. SQLite's `flushed = 1` bookkeeping proved
    only "this function believes it once wrote this content," never
    "this content is still actually there."

    Antigravity Audit #71 (AUDIT-P0-03) fix: independently reproduced --
    the prior version of this check trusted file SIZE alone
    (`actual_size >= safe_offset`). Replacing a flushed shard file's
    content with equal-size (or larger) junk bytes -- a bit-flip, a
    block of padding, or arbitrary substituted text -- passed this check
    completely undetected, since size alone says nothing about content.
    Now ALSO compares the file's actual SHA-256 digest (over exactly the
    first `safe_byte_offset` bytes -- see `_hash_file_prefix()`'s own
    docstring for why only that prefix, not the whole current file, is
    hashed here) against the digest recorded at the moment those bytes
    were durably written (`_flush_pending_shard_rows()`). The recorded
    digest is the TRUSTWORTHY reference precisely because THIS module
    computed it itself, from bytes it had just written and fsync'd --
    never from a caller-supplied claim; this is "only regenerate data
    from a source valid under the documented threat model." A mismatch
    (content tampered without changing size, or any other equal-or-
    larger-size substitution) is now treated exactly like a missing
    file.

    Run at the START of every `process_corpus()` call (before
    `_truncate_partial_shard_writes()`, which only handles partial/
    corrupt TRAILING bytes past a known-good offset, not corruption
    WITHIN that offset): for every shard file this `output_dir` has ever
    recorded a safe byte offset/digest for, if that file is missing,
    smaller than the recorded offset, OR its content digest no longer
    matches, every `kept_records` row that maps to it is reset to
    `flushed = 0` and its safe-offset/digest record is reset to
    0/empty -- so the next `_flush_pending_shard_rows()` call
    regenerates it from SQLite's OWN durable `kept_records` truth (never
    from the corrupted file itself, which is re-verified again once
    rewritten), rather than silently reporting success over missing or
    tampered output."""
    recorded = conn.execute("SELECT path, safe_byte_offset, safe_byte_digest FROM shard_file_safe_offsets").fetchall()
    if not recorded:
        return
    distinct_shards = conn.execute("SELECT DISTINCT shard, split FROM kept_records").fetchall()
    path_to_shard_split = {str(_shard_path(output_dir, shard, split)): (shard, split) for shard, split in distinct_shards}

    for path_str, safe_offset, safe_digest in recorded:
        p = Path(path_str)
        actual_size = p.stat().st_size if p.exists() else -1
        if actual_size >= safe_offset and _hash_file_prefix(p, safe_offset) == safe_digest:
            continue  # present, at least as large as flushed, AND content-verified -- genuinely fine
        shard_split = path_to_shard_split.get(path_str)
        if shard_split is None:
            continue  # no kept_records row maps here (nothing to recover)
        shard, split = shard_split
        conn.execute("BEGIN")
        conn.execute("UPDATE kept_records SET flushed = 0 WHERE shard = ? AND split = ?", (shard, split))
        conn.execute(
            "INSERT INTO shard_file_safe_offsets (path, safe_byte_offset, safe_byte_digest) VALUES (?, 0, ?) "
            "ON CONFLICT(path) DO UPDATE SET safe_byte_offset = 0, safe_byte_digest = excluded.safe_byte_digest",
            (path_str, _EMPTY_SHA256),
        )
        conn.execute("COMMIT")


def _flush_pending_shard_rows(output_dir: Path, conn: sqlite3.Connection) -> None:
    """Idempotent: appends every `kept_records` row with `flushed = 0` to
    its target shard file, in bounded pages (never loading the whole
    table into memory).

    Crash safety requires recording each file's PRE-write byte offset
    and COMMITTING that BEFORE attempting the write -- not only
    recording the post-write size afterward. If the safe offset were
    only ever recorded after a successful write, a crash during the
    very FIRST write to a given shard file (nothing previously
    recorded for it at all) would leave `_truncate_partial_shard_writes()`
    with no reference offset to truncate back to, so a retried flush
    would re-append on top of already-landed (but unmarked) bytes,
    producing a duplicate line -- reproduced directly by this module's
    own test suite before this fix. Recording the pre-write offset
    first means ANY failure between that commit and the final
    flushed=1 update is recovered identically: truncate back to the
    last known-good offset, then redo the flush from SQLite's own
    durable truth.

    Antigravity Audit #71 (AUDIT-P0-03) fix: the pre-write record now
    ALSO captures the CURRENT file's own content digest (hashing exactly
    its pre-write byte count -- the same prefix `_truncate_partial_shard_writes()`
    would restore it to on a crash between this record and the write
    below, so the recorded digest stays valid for post-crash recovery
    verification even if this write is interrupted), and the post-write
    record captures the digest of the file's new, full content after the
    append -- both streamed, never loading the whole file into memory at
    once (`_hash_file_prefix()`). These are the trustworthy reference
    digests `_verify_and_recover_missing_or_corrupted_shard_output()`
    later verifies real on-disk bytes against."""
    page_size = 500
    while True:
        rows = conn.execute("SELECT seq, shard, split, normalized_text FROM kept_records WHERE flushed = 0 ORDER BY seq LIMIT ?", (page_size,)).fetchall()
        if not rows:
            break
        by_file: dict[Path, list[tuple[int, str]]] = {}
        for seq, shard, split, text in rows:
            by_file.setdefault(_shard_path(output_dir, shard, split), []).append((seq, text))

        for path in by_file:
            path.parent.mkdir(parents=True, exist_ok=True)
            pre_write_size = path.stat().st_size if path.exists() else 0
            pre_write_digest = _hash_file_prefix(path, pre_write_size)
            conn.execute("BEGIN")
            conn.execute(
                "INSERT INTO shard_file_safe_offsets (path, safe_byte_offset, safe_byte_digest) VALUES (?, ?, ?) "
                "ON CONFLICT(path) DO UPDATE SET safe_byte_offset = excluded.safe_byte_offset, safe_byte_digest = excluded.safe_byte_digest",
                (str(path), pre_write_size, pre_write_digest),
            )
            conn.execute("COMMIT")

        conn.execute("BEGIN")
        for path, entries in by_file.items():
            payload = "".join(json.dumps({"text": t}, ensure_ascii=False) + "\n" for _, t in entries).encode("utf-8")
            with open(path, "ab") as f:
                f.write(payload)
                f.flush()
                os.fsync(f.fileno())
            path.chmod(0o600)
            new_size = path.stat().st_size
            new_digest = _hash_file_prefix(path, new_size)
            conn.execute(
                "INSERT INTO shard_file_safe_offsets (path, safe_byte_offset, safe_byte_digest) VALUES (?, ?, ?) "
                "ON CONFLICT(path) DO UPDATE SET safe_byte_offset = excluded.safe_byte_offset, safe_byte_digest = excluded.safe_byte_digest",
                (str(path), new_size, new_digest),
            )
        seqs = [seq for seq, _, _, _ in rows]
        conn.executemany("UPDATE kept_records SET flushed = 1 WHERE seq = ?", [(s,) for s in seqs])
        conn.execute("COMMIT")


def iter_kept_records(output_dir: Path, *, page_size: int = 1000) -> Iterator[str]:
    """P1-01 fix: the genuinely bounded-memory way to consume a
    processed corpus's kept records -- a generator that pages through
    the durable SQLite store (never materializing more than `page_size`
    records in memory at once), for a caller whose corpus is too large
    to hold the full `kept_records` list `process_corpus()` otherwise
    returns. Safe to call at any time against a completed (or even
    partially-flushed -- this reads `kept_records` directly, not only
    `flushed` rows, since the SQLite table is the authoritative "was
    this record actually kept" truth regardless of whether its shard
    file has been written yet) `output_dir`."""
    conn = sqlite3.connect(output_dir / PROGRESS_DB_NAME)
    try:
        last_seq = 0
        while True:
            rows = conn.execute(
                "SELECT seq, normalized_text FROM kept_records WHERE seq > ? ORDER BY seq LIMIT ?", (last_seq, page_size),
            ).fetchall()
            if not rows:
                break
            for _, text in rows:
                yield text
            last_seq = rows[-1][0]
    finally:
        conn.close()


def process_corpus(
    input_path: Path, output_dir: Path, *, num_shards: int, resume_from_line: int | None = None,
    quality_filter: Callable[[str], bool] | None = None, enforce_pii_screening: bool = True,
    commit_batch_size: int = DEFAULT_COMMIT_BATCH_SIZE, return_kept_records: bool = True,
) -> tuple[ProcessingReport, list[str]]:
    """The full pipeline stage: stream -> corrupt-record rejection ->
    normalize -> exact + bounded-window near-duplicate rejection ->
    quality filter -> PII/secret screening -> deterministic shard+split
    assignment -> durable, bounded-memory, crash-safe commit.

    `resume_from_line`: if omitted (the default), automatically resumes
    from this `output_dir`'s own durably recorded progress (0 for a
    fresh `output_dir`) -- a caller does not need to track or pass this
    manually. Passing it explicitly overrides the recorded progress
    (mainly for tests exercising a specific resume point).

    Returns `(report, kept_records)`. `kept_records` is this function's
    own bounded, in-memory re-read of ALL kept records from the durable
    SQLite store after processing completes (paged, not loaded as one
    giant string at any point), preserved by DEFAULT for exact backward
    compatibility with existing callers (e.g. manifest-building code)
    that consume the full list. **P1-01 fix**: the PROCESSING loop
    itself (the actual bottleneck for a huge corpus) never holds more
    than `commit_batch_size` records in memory regardless of this flag
    -- but the prior version of this function's COMPATIBILITY INTERFACE
    still unconditionally re-materialized the full kept-records list
    into memory before returning, defeating bounded-memory operation for
    any caller who didn't need that list back at all. Pass
    `return_kept_records=False` for a genuinely bounded-memory call
    (returns `(report, [])`); a caller still needing the records should
    use `iter_kept_records(output_dir)` afterward, a generator that pages
    through SQLite rather than materializing the whole list at once."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    # P0-02 fix: independently confirmed as a real risk by inspection --
    # two process_corpus() calls targeting the SAME output_dir with no
    # mutual exclusion could both read the same resume_offset and
    # process overlapping line ranges concurrently; whichever commits
    # its progress LAST would silently "un-progress" the other's
    # already-committed advancement. An exclusive flock on a dedicated
    # lock file, held for this call's ENTIRE duration (not merely around
    # individual SQLite transactions), serializes concurrent callers
    # against the same output_dir -- the same exclusive-writer
    # discipline `orca.genesis.training.primitives.save_training_state`
    # already established for checkpoint files, applied here to a
    # whole-directory granularity instead of one file.
    lock_path = output_dir / ".process_corpus.lock"
    lock_file = open(lock_path, "a+")
    fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
    conn = _open_progress_db(output_dir)
    try:
        _verify_and_recover_missing_or_corrupted_shard_output(output_dir, conn)  # P0-03: detect externally deleted/truncated output
        _truncate_partial_shard_writes(output_dir, conn)
        _flush_pending_shard_rows(output_dir, conn)  # finish any batch a prior crash committed to SQLite but never flushed to disk

        report = _load_progress(conn)
        start_line = report.resume_offset if resume_from_line is None else resume_from_line

        seen_exact_cache: set[str] = set()  # a small, same-batch cache only -- see note below; not the durable source of truth
        near_dup_window: list[tuple[int, str, frozenset]] = _load_near_dup_window_tail(conn)  # P0-02: inherit the real tail, not an empty window
        pending: list[tuple[str, int, str, str]] = []  # (exact_key, shard, split, normalized_text), bounded to commit_batch_size

        def _is_seen_exact(key: str) -> bool:
            if key in seen_exact_cache:
                return True
            row = conn.execute("SELECT 1 FROM seen_exact WHERE exact_key = ?", (key,)).fetchone()
            return row is not None

        def _commit_batch() -> None:
            # Antigravity Audit #71 (AUDIT-P0-02): independently reproduced
            # as a real defect, not merely inspected -- this early return
            # on an empty `pending` (kept records only) silently discarded
            # the progress row, rejection counters, and near-dup window for
            # every batch boundary where nothing was KEPT: a corpus that is
            # all corrupt/rejected/duplicate records, or a trailing run of
            # such records after the last kept batch, left NOTHING
            # committed to SQLite at all -- `report.resume_offset` and
            # every rejection counter reverted to whatever (possibly
            # none) a PRIOR batch had committed, so a resume re-read lines
            # already accounted for, double-counting rejections and
            # re-scanning already-seen input. Progress must be persisted
            # at every batch boundary and at loop exit regardless of
            # whether any record was KEPT -- `pending` only ever holds
            # records that passed every filter, so gating durability on it
            # being non-empty conflated "nothing to flush to a shard file"
            # with "nothing to persist," which are not the same thing.
            conn.execute("BEGIN")
            for exact_key, shard, split, text in pending:
                conn.execute("INSERT OR IGNORE INTO seen_exact (exact_key) VALUES (?)", (exact_key,))
                conn.execute("INSERT INTO kept_records (shard, split, normalized_text) VALUES (?, ?, ?)", (shard, split, text))
            conn.execute(
                "INSERT INTO progress (id, resume_offset, lines_read, corrupt_records, exact_duplicates, near_duplicates, "
                "quality_rejected, pii_secret_rejected, kept) VALUES (0, ?, ?, ?, ?, ?, ?, ?, ?) "
                "ON CONFLICT(id) DO UPDATE SET resume_offset=excluded.resume_offset, lines_read=excluded.lines_read, "
                "corrupt_records=excluded.corrupt_records, exact_duplicates=excluded.exact_duplicates, "
                "near_duplicates=excluded.near_duplicates, quality_rejected=excluded.quality_rejected, "
                "pii_secret_rejected=excluded.pii_secret_rejected, kept=excluded.kept",
                (report.resume_offset, report.lines_read, report.corrupt_records, report.exact_duplicates,
                 report.near_duplicates, report.quality_rejected, report.pii_secret_rejected, report.kept),
            )
            # P0-02: persist the near-dup window's CURRENT state in the
            # same transaction/commit boundary as everything else -- a
            # crash between commits loses at most one batch's worth of
            # window state, the same bounded trade-off every other piece
            # of durable state in this function already makes.
            conn.execute("DELETE FROM near_dup_window")
            conn.executemany(
                "INSERT INTO near_dup_window (line_number, normalized_text) VALUES (?, ?)",
                [(ln, text) for ln, text, _ in near_dup_window],
            )
            conn.execute("COMMIT")
            pending.clear()
            seen_exact_cache.clear()
            _flush_pending_shard_rows(output_dir, conn)

        for line_number, raw_text in stream_records(input_path, resume_from_line=start_line):
            report.lines_read += 1
            report.resume_offset = line_number + 1
            if not raw_text:
                report.record_corrupt(f"line {line_number}: malformed JSON or missing/empty 'text' field")
                continue

            normalized = normalize_record_text(raw_text)
            exact_key = hashlib.sha256(normalize_text(normalized).encode("utf-8")).hexdigest()
            if _is_seen_exact(exact_key):
                report.exact_duplicates += 1
                continue

            shingles = frozenset(word_ngrams(normalized, NEAR_DUP_WORD_NGRAM))
            near_dup_window.append((line_number, normalized, shingles))
            if len(near_dup_window) > NEAR_DUP_WINDOW:
                near_dup_window.pop(0)

            is_near_dup = False
            for _, _, other_shingles in near_dup_window[:-1]:
                if jaccard(shingles, other_shingles) >= NEAR_DUP_JACCARD_THRESHOLD:
                    is_near_dup = True
                    break
            if is_near_dup:
                report.near_duplicates += 1
                near_dup_window.pop()
                continue

            if quality_filter is not None and not quality_filter(normalized):
                report.quality_rejected += 1
                continue

            if enforce_pii_screening:
                sanitized = sanitize_for_candidate(normalized)
                if sanitized.rejected:
                    report.pii_secret_rejected += 1
                    continue
                normalized = sanitized.clean_text

            shard = deterministic_shard(normalized, num_shards=num_shards)
            split = deterministic_split(normalized)
            pending.append((exact_key, shard, split, normalized))
            seen_exact_cache.add(exact_key)
            report.kept += 1

            if len(pending) >= commit_batch_size:
                _commit_batch()

        _commit_batch()

        kept_records: list[str] = []
        if return_kept_records:
            page_size = 1000
            last_seq = 0
            while True:
                rows = conn.execute("SELECT seq, normalized_text FROM kept_records WHERE seq > ? ORDER BY seq LIMIT ?", (last_seq, page_size)).fetchall()
                if not rows:
                    break
                kept_records.extend(text for _, text in rows)
                last_seq = rows[-1][0]

        return report, kept_records
    finally:
        conn.close()
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)
        lock_file.close()


def compute_shard_digests(output_dir: Path) -> dict[str, str]:
    """A-10 (Workstream A hardening): real, independently-recomputable
    SHA-256 digests of the ACTUAL processed shard files written by
    `process_corpus()` to `output_dir` -- streamed in fixed-size chunks
    (never loading a whole shard file into memory at once), keyed by
    filename so the mapping is stable regardless of directory-listing
    order. This is the concrete artifact a caller should pass as
    `GenesisTrainingRun.validate()`'s `authorized_shard_digests`
    (Mission 2's M2-03 fix) -- a REAL digest of the bytes a training job
    would actually read, not an arbitrary caller-supplied string.
    Changing a single byte in any shard file changes that file's own
    digest, which (via `GenesisTrainingRun.authorize()`'s exact-match
    binding check) invalidates any grant authorized against the
    PREVIOUS digest -- demonstrated directly in this module's own test
    suite."""
    digests: dict[str, str] = {}
    for path in sorted(output_dir.glob("shard-*.jsonl")):
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1024 * 1024), b""):
                h.update(chunk)
        digests[path.name] = h.hexdigest()
    return digests
