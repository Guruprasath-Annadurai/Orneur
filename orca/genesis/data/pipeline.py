"""
GENESIS Foundation Sprint 2, Workstream A, Mission A2: a real, executable,
CPU-testable streaming data-processing pipeline for native pretraining
text records.

Reuses existing, already-tested infrastructure rather than duplicating it:
`orca.eval.genesis_contamination.normalize_text`/`word_ngrams`/`jaccard`
for near-duplicate detection (the same algorithmic approach the Genesis
Capability Eval V1 corpus's own contamination control already uses, here
applied to raw pretraining records rather than eval-corpus items), and
`orca.learning.sanitize.sanitize_for_candidate` for PII/secret screening
(the same DLP path `orca.learning.pipeline`'s curriculum pipeline already
uses, reused rather than reimplemented). The atomic-write discipline below
(`tempfile.mkstemp` + `fsync` + `os.replace`) matches the pattern
established in `orca.genesis.training.primitives.save_training_state`
(Sprint 1) -- re-implemented here rather than imported, since that
specific helper is private to the training-primitives module and this is
a genuinely different artifact (a processed shard file, not a checkpoint).

Deliberately O(n^2) near-duplicate detection within a bounded window: this
is a CPU-testable reference implementation proving the mechanism and
contract correctness, not a production-scale pipeline. A real multi-GB
corpus would need MinHash/LSH-based near-duplicate detection; that
algorithmic upgrade is a drop-in replacement for `_find_near_duplicates`
below, not a change to this module's public contract.

## A-07/A-08 hardening (Native-Authorization-Convergence Workstream A)

The original version of `process_corpus()` accumulated THREE unbounded,
corpus-size-proportional structures in memory: `seen_exact` (a Python
`set` growing by one entry per unique record in the ENTIRE corpus),
`kept_records` (every kept record's full normalized text, held for the
caller's manifest-building use), and `shard_writers` (every kept record's
text, bucketed by shard+split, written to disk only ONCE at the very end
via a single `os.replace()` per shard file). This meant: (1) peak memory
scaled linearly with corpus size, not boundedly, and (2) a crash or
interruption at ANY point before that final write loop produced ZERO
output and left no durable, resumable progress record at all; (3) even a
"successful" resume into an EXISTING `output_dir` would silently
OVERWRITE each shard file's prior content via `os.replace()`, discarding
everything a previous run had already committed.

Fixed via a SQLite-backed durable store (`_progress.sqlite3`, one file
per `output_dir`) that is the SINGLE source of truth for: the exact-dedup
set, every kept record's (shard, split, text) assignment, and progress
(the last input line fully committed). Records are processed one at a
time with only a BOUNDED in-memory batch buffer (`commit_batch_size`,
default 200) held at once; each batch commits to SQLite as ONE atomic
transaction (dedup-set inserts + kept-record inserts + progress update
together), so a crash mid-batch loses at most `commit_batch_size`
records' worth of work -- which is safely REDONE from scratch on resume
(SQLite's own transactional durability guarantees the batch was either
fully applied or not applied at all, never partially). Shard `.jsonl`
files are regenerated by a separate, idempotent flush step that reads
only not-yet-flushed rows from SQLite (itself paged, never loading the
whole table) and APPENDS them -- never truncates or replaces existing
file content -- with a recorded "last known-good byte offset" per file so
a resume can first truncate away any partially-written trailing bytes
from an interrupted append before redoing it cleanly from the durable
SQLite truth. This closes all three original gaps: peak memory is now
O(`commit_batch_size` + near-dup window), a crash loses at most one
batch's work (never silently duplicated, never silently lost), and a
resumed run APPENDS to -- never overwrites -- prior committed output.
"""
