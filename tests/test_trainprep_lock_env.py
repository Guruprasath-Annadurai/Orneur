"""Workstream G #1 and #2 (register TRAIN-1): the hash-locked `train` dependency set and the deterministic environment manifest.
The trainer stack is NEVER installed or imported here -- these tests only read text."""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

from orca.train.dryrun.canon import sha256_hex
from orca.train.dryrun.envmanifest import EnvManifestInvalid, build_env_manifest, env_manifest_bytes, verify_env_manifest
from orca.train.dryrun.lockcheck import check_lock_file, check_lock_text, train_extra_requirements

REPO = Path(__file__).resolve().parent.parent
LOCK = REPO / "requirements" / "train.txt"
H = "--hash=sha256:" + "ab" * 32
HDR = "# This file was autogenerated by uv via the following command:\n#    uv pip compile pyproject.toml --extra train --generate-hashes --python-version 3.11\n"


# ── the committed lock ──────────────────────────────────────────────────────────────────────────────────────────────────────────

def test_committed_train_lock_is_structurally_valid_and_covers_the_train_extra():
    rep = check_lock_file(LOCK, required_names=train_extra_requirements(REPO / "pyproject.toml"))
    assert rep.ok, rep.problems
    assert rep.packages >= 100 and rep.hashes >= rep.packages
    for core in ("torch", "transformers", "trl", "peft", "unsloth", "bitsandbytes", "accelerate", "datasets", "wandb", "scipy"):
        assert core in rep.names, core


def test_committed_lock_header_records_the_exact_command_python_and_platform():
    head = LOCK.read_text().splitlines()[:2]
    assert "--generate-hashes" in head[1] and "--python-version 3.11" in head[1] and "--python-platform x86_64-manylinux_2_28" in head[1]
    assert "--extra train" in head[1]


def test_every_requirement_line_is_double_equals_pinned_and_hashed():
    text = LOCK.read_text()
    reqs = [ln for ln in text.splitlines() if ln and not ln.startswith((" ", "#"))]
    assert reqs and all("==" in r and r.rstrip().endswith("\\") for r in reqs)          # `name==ver \` followed by hash lines
    assert not any(tok in text for tok in ("git+", "://", " @ ", "--index-url", "--extra-index-url", "-e "))


def test_train_extra_requirements_skip_marker_gated_entries():
    names = train_extra_requirements(REPO / "pyproject.toml")
    assert "setuptools" not in names and {"unsloth", "trl", "transformers", "datasets", "peft", "bitsandbytes", "accelerate"} <= set(names)


# ── the verifier rejects every way a lock can be weakened ───────────────────────────────────────────────────────────────────────

def _lock(body: str) -> str:
    return HDR + body


GOOD = _lock(f"alpha==1.0 \\\n    {H}\n    # via x\nbeta==2.0 ; python_full_version >= '3.11' \\\n    {H}\n")


def test_verifier_accepts_a_well_formed_lock():
    rep = check_lock_text(GOOD)
    assert rep.ok and rep.packages == 2 and rep.hashes == 2


@pytest.mark.parametrize("name,text,code", [
    ("range_pin", _lock(f"alpha>=1.0 \\\n    {H}\n"), "NOT_PINNED_WITH_DOUBLE_EQUALS"),
    ("compatible_pin", _lock(f"alpha~=1.0 \\\n    {H}\n"), "NOT_PINNED_WITH_DOUBLE_EQUALS"),
    ("unpinned", _lock(f"alpha \\\n    {H}\n"), "NOT_PINNED_WITH_DOUBLE_EQUALS"),
    ("no_hash", _lock("alpha==1.0\n"), "NO_HASH_FOR_alpha"),
    ("short_hash", _lock("alpha==1.0 \\\n    --hash=sha256:abcd\n"), "BAD_HASH_FOR_alpha"),
    ("upper_hash", _lock("alpha==1.0 \\\n    --hash=sha256:" + "AB" * 32 + "\n"), "BAD_HASH_FOR_alpha"),
    ("md5_hash", _lock("alpha==1.0 \\\n    --hash=md5:" + "ab" * 16 + "\n"), "BAD_HASH_FOR_alpha"),
    ("url", _lock(f"alpha @ https://example.invalid/a.whl \\\n    {H}\n"), "URL_OR_VCS_REQUIREMENT"),
    ("vcs", _lock(f"git+https://example.invalid/a.git \\\n    {H}\n"), "URL_OR_VCS_REQUIREMENT"),
    ("editable", _lock(f"-e . \\\n    {H}\n"), "FORBIDDEN_OPTION"),
    ("index_override", _lock(f"--index-url https://evil.invalid/simple \\\n    {H}\nalpha==1.0 \\\n    {H}\n"), "FORBIDDEN_OPTION"),
    ("nested_include", _lock(f"-r other.txt\nalpha==1.0 \\\n    {H}\n"), "FORBIDDEN_OPTION"),
    ("duplicate", _lock(f"alpha==1.0 \\\n    {H}\nAlpha==1.1 \\\n    {H}\n"), "DUPLICATE_alpha"),
    ("empty", HDR, "EMPTY_LOCK"),
    ("not_hash_compiled", "alpha==1.0 \\\n    " + H + "\n", "HEADER_MISSING_GENERATE_HASHES_COMMAND"),
    ("dangling_continuation", _lock("alpha==1.0 \\\n"), "UNTERMINATED_CONTINUATION"),
])
def test_verifier_rejects(name, text, code):
    rep = check_lock_text(text)
    assert not rep.ok and any(p.startswith(code) for p in rep.problems), (name, rep.problems)


def test_verifier_rejects_a_lock_missing_a_required_train_package():
    rep = check_lock_text(GOOD, required_names=["alpha", "torch"])
    assert not rep.ok and "REQUIRED_PACKAGE_NOT_LOCKED_torch" in rep.problems


def test_package_names_are_normalized_when_checking_requirements():
    rep = check_lock_text(_lock(f"Unsloth_Zoo==1.0 \\\n    {H}\n"), required_names=["unsloth-zoo"])
    assert rep.ok


def test_verifier_script_exit_codes_and_it_never_imports_the_trainer_stack(tmp_path):
    ok = subprocess.run([sys.executable, "scripts/trainprep/verify_train_lock.py"], cwd=REPO, capture_output=True, text=True)
    assert ok.returncode == 0 and json.loads(ok.stdout)["ok"] is True
    bad = tmp_path / "bad.txt"
    bad.write_text(_lock("torch>=2\n"))
    res = subprocess.run([sys.executable, "scripts/trainprep/verify_train_lock.py", "--lock", str(bad)], cwd=REPO, capture_output=True, text=True)
    assert res.returncode == 1 and json.loads(res.stdout)["ok"] is False
    probe = subprocess.run([sys.executable, "-c", "import runpy,sys,io,contextlib\nsys.argv=['v']\n"
                            "with contextlib.redirect_stdout(io.StringIO()):\n    try: runpy.run_path('scripts/trainprep/verify_train_lock.py', run_name='__main__')\n    except SystemExit: pass\n"
                            "print([m for m in sys.modules if m.split('.')[0] in ('torch','transformers','trl','peft','unsloth','bitsandbytes','accelerate','datasets')])"],
                           cwd=REPO, capture_output=True, text=True)
    assert probe.stdout.strip() == "[]", probe.stderr


# ── environment manifest ────────────────────────────────────────────────────────────────────────────────────────────────────────

SHA40, SHA64 = "1" * 40, "2" * 64
PY = {"version": "3.11.17", "implementation": "CPython"}
PLAT = {"system": "Linux", "machine": "x86_64"}


def _build(**over):
    kw = dict(code_sha=SHA40, dataset_bundle_sha256=SHA64, seeds={"seed": 1234, "data_seed": 99}, lock_path=LOCK, python_info=PY, platform_info=PLAT)
    kw.update(over)
    return build_env_manifest(**kw)


def test_env_manifest_is_deterministic_and_canonical():
    a, b = _build(), _build(seeds={"data_seed": 99, "seed": 1234})
    assert env_manifest_bytes(a) == env_manifest_bytes(b)
    assert env_manifest_bytes(a) == env_manifest_bytes(json.loads(env_manifest_bytes(a)))              # round-trips to the same bytes
    assert a["manifest_sha256"] == sha256_hex(json.dumps({k: v for k, v in a.items() if k != "manifest_sha256"}, sort_keys=True, separators=(",", ":")).encode())


def test_env_manifest_contents():
    m = _build()
    assert m["python"] == PY and m["platform"] == PLAT and m["code_sha"] == SHA40 and m["dataset_bundle_sha256"] == SHA64
    assert m["seeds"] == {"data_seed": 99, "seed": 1234} and m["synthetic"] is True
    assert m["container"] == {"image_digest": None, "status": "NOT_BUILT"}                              # never a fabricated digest
    assert m["lock"]["sha256"] == sha256_hex(LOCK.read_bytes()) and m["lock"]["structure_ok"] is True and m["lock"]["path"] == "requirements/train.txt"
    assert not {"created_at", "timestamp", "hostname", "user", "cwd"} & set(json.dumps(m))
    assert verify_env_manifest(m) == []


def test_every_input_changes_the_manifest_hash():
    base = _build()["manifest_sha256"]
    for over in (dict(code_sha="3" * 40), dict(dataset_bundle_sha256="4" * 64), dict(seeds={"seed": 1}), dict(python_info={**PY, "version": "3.12.0"}),
                 dict(platform_info={**PLAT, "machine": "arm64"})):
        assert _build(**over)["manifest_sha256"] != base, over


def test_lock_content_change_changes_the_manifest(tmp_path):
    other = tmp_path / "train.txt"
    other.write_text(LOCK.read_text() + "# edited\n")
    assert _build(lock_path=other)["manifest_sha256"] != _build()["manifest_sha256"]


def test_injected_facts_are_validated_not_guessed():
    for bad in (dict(code_sha="HEAD"), dict(code_sha="1" * 39), dict(dataset_bundle_sha256="x"), dict(seeds={}), dict(seeds={"seed": True}),
                dict(seeds={"seed": 1.5}), dict(seeds=None)):
        with pytest.raises(EnvManifestInvalid):
            _build(**bad)


def test_verify_detects_tampering_and_fabricated_container_digest():
    m = _build()
    assert verify_env_manifest({**m, "code_sha": "9" * 40}) == ["SELF_HASH_MISMATCH"]
    forged = {**m, "container": {"image_digest": "sha256:" + "a" * 64, "status": "BUILT"}}
    body = {k: v for k, v in forged.items() if k != "manifest_sha256"}
    from orca.train.dryrun.canon import hash_obj
    forged["manifest_sha256"] = hash_obj(body)                                   # self-consistent, but claims an image that does not exist
    assert verify_env_manifest(forged) == ["CONTAINER_DIGEST_NOT_PLACEHOLDER"]
    assert verify_env_manifest({"x": 1}) == ["SCHEMA_MISMATCH"]


def test_env_manifest_script_is_byte_deterministic_across_processes():
    cmd = [sys.executable, "scripts/trainprep/env_manifest.py", "--code-sha", SHA40, "--dataset-bundle-sha256", SHA64, "--seed", "7"]
    a, b = subprocess.run(cmd, cwd=REPO, capture_output=True), subprocess.run(cmd, cwd=REPO, capture_output=True)
    assert a.returncode == b.returncode == 0 and a.stdout == b.stdout and verify_env_manifest(json.loads(a.stdout)) == []
    missing = subprocess.run([sys.executable, "scripts/trainprep/env_manifest.py"], cwd=REPO, capture_output=True)
    assert missing.returncode == 2                                               # required facts are never defaulted
