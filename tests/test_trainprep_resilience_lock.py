"""Resilience #1: dependency-lock verification beyond structure -- duplicate/shared hashes, per-spec coverage (unlocked / version-violating
dependency refused) and lock drift against the env manifest. Reads text only; no trainer package is installed or imported."""
from __future__ import annotations

from pathlib import Path

import pytest

from orca.train.dryrun.envmanifest import build_env_manifest
from orca.train.dryrun.lockverify import LockRefused, check_lock_consistency, declared_train_specs, require_verified_lock, verify_lock

REPO = Path(__file__).resolve().parent.parent
LOCK = REPO / "requirements" / "train.txt"
HDR = "# autogenerated by uv\n#    uv pip compile pyproject.toml --extra train --generate-hashes --python-version 3.11\n"
A, B, C = ("--hash=sha256:" + c * 64 for c in "abc")


def lock(*pkgs):
    out = HDR
    for name, ver, hashes in pkgs:
        out += f"{name}=={ver} \\\n" + " \\\n".join(f"    {h}" for h in hashes) + "\n"
    return out


GOOD = lock(("alpha", "1.2.0", [A]), ("beta", "2.0", [B]))


def test_committed_lock_is_consistent_and_covers_the_declared_train_extra_with_versions():
    text = LOCK.read_text()
    assert check_lock_consistency(text) == []
    v = verify_lock(text, declared=declared_train_specs(REPO / "pyproject.toml"))
    assert v.ok, v.problems


def test_duplicate_hash_inside_one_package_is_refused():
    assert "DUPLICATE_HASH_IN_alpha" in check_lock_consistency(lock(("alpha", "1.0", [A, A])))


def test_one_hash_shared_by_two_packages_is_refused():
    assert "HASH_SHARED_BY_alpha_AND_beta" in check_lock_consistency(lock(("alpha", "1.0", [A]), ("beta", "1.0", [A])))


def test_structural_problems_are_surfaced_by_verify_lock_too():
    assert "NO_HASH_FOR_alpha" in verify_lock(HDR + "alpha==1.0\n").problems
    assert not verify_lock(HDR + "alpha>=1.0 \\\n    " + A + "\n").ok


@pytest.mark.parametrize("spec,code", [("gamma>=1", "UNLOCKED_DEPENDENCY_gamma"), ("alpha>=2", "LOCKED_VERSION_VIOLATES_alpha"),
                                       ("alpha==1.2.1", "LOCKED_VERSION_VIOLATES_alpha"), ("alpha[x]<1", "LOCKED_VERSION_VIOLATES_alpha")])
def test_unlocked_or_version_violating_dependency_is_refused(spec, code):
    assert code in verify_lock(GOOD, declared=[spec]).problems


def test_declared_specs_satisfied_by_the_lock_are_accepted():
    assert verify_lock(GOOD, declared=["alpha>=1", "Beta ==2.0", "alpha~=1.2"]).ok


def test_an_unparseable_declared_spec_fails_closed():
    assert "UNPARSEABLE_DECLARED_SPEC" in "".join(verify_lock(GOOD, declared=["alpha>>>1"]).problems)


def test_lock_sha_bound_elsewhere_must_match():
    assert "LOCK_SHA_MISMATCH" in verify_lock(GOOD, bound_sha256="0" * 64).problems


def _manifest(lock_path):
    return build_env_manifest(code_sha="a" * 40, dataset_bundle_sha256="b" * 64, seeds={"s": 1}, lock_path=lock_path)


def test_lock_drift_after_the_env_manifest_was_built_is_refused(tmp_path):
    p = tmp_path / "train.txt"
    p.write_text(GOOD)
    man = _manifest(p)
    assert require_verified_lock(p, man) is not None
    p.write_text(GOOD.replace("2.0", "2.1"))                                # a reviewed-then-edited lock
    with pytest.raises(LockRefused) as e:
        require_verified_lock(p, man)
    assert "LOCK_DRIFT" in e.value.problems


def test_a_lock_that_stops_being_valid_is_refused_even_if_the_manifest_matches(tmp_path):
    p = tmp_path / "train.txt"
    p.write_text(HDR + f"alpha==1.2.0 \\\n    {A}\nbeta==2.0\n")             # hashless package
    with pytest.raises(LockRefused) as e:
        require_verified_lock(p, _manifest(p))
    assert "NO_HASH_FOR_beta" in e.value.problems


def test_a_tampered_env_manifest_is_refused(tmp_path):
    p = tmp_path / "train.txt"
    p.write_text(GOOD)
    man = dict(_manifest(p))
    man["seeds"] = {"s": 2}
    with pytest.raises(LockRefused) as e:
        require_verified_lock(p, man)
    assert "SELF_HASH_MISMATCH" in e.value.problems
